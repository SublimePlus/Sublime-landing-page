/**
 * Compiles `content/blog/*.md` into `src/lib/blog-data.ts`.
 *
 * Why this exists: the site deploys to Cloudflare Workers through OpenNext,
 * and no incremental cache is configured, so pages re-render inside the Worker
 * on request rather than being served as prerendered HTML. A Worker has no
 * filesystem — reading `content/` at request time fails with
 * `no such file or directory, readdir '/bundle/content/blog'` — and workerd
 * forbids the runtime `eval` that a Markdown/MDX compiler needs. So both the
 * file reads and the Markdown compile happen here, at build time, and the
 * result is a plain TypeScript module the bundler can inline.
 *
 * Posts are Markdown, not MDX: they compile to HTML here, so a JSX component
 * written in a post would be escaped rather than rendered. Supporting
 * components again means compiling to a React component at build time (for
 * example `@next/mdx`), not rendering MDX inside the Worker.
 *
 * Runs automatically via the `predev` / `prebuild:next` npm scripts. The
 * generated file is committed so a fresh clone typechecks without a build;
 * every build regenerates it, so a stale copy cannot ship.
 */
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import readingTime from "reading-time";
import { unified } from "unified";
import remarkParse from "remark-parse";
import remarkRehype from "remark-rehype";
import rehypeStringify from "rehype-stringify";

const ROOT = process.cwd();
const BLOG_DIR = path.join(ROOT, "content/blog");
const OUT_FILE = path.join(ROOT, "src/lib/blog-data.ts");

const TONES = ["teal", "pine", "lime"];
/** Same rule as COVER_RE in src/lib/admin/posts.ts. */
const COVER_RE = /^\/blog-images\/[a-z0-9-]+\.(?:png|jpe?g|webp|gif)$/;
const ORDER_FILE = path.join(BLOG_DIR, "order.json");

const processor = unified()
  .use(remarkParse)
  // The posts are trusted repo content, not user input, so raw HTML passing
  // through would be safe — but nothing needs it, so it stays disallowed.
  .use(remarkRehype)
  .use(rehypeStringify);

function compile(slug, source) {
  const { data, content } = matter(source);

  for (const field of ["title", "excerpt", "date"]) {
    if (!data[field]) {
      throw new Error(`content/blog/${slug}.md is missing "${field}" in its frontmatter`);
    }
  }
  if (data.tone && !TONES.includes(data.tone)) {
    throw new Error(
      `content/blog/${slug}.md has tone "${data.tone}"; expected one of ${TONES.join(", ")}`
    );
  }
  if (Number.isNaN(new Date(data.date).getTime())) {
    throw new Error(`content/blog/${slug}.md has an unparseable date "${data.date}"`);
  }

  // A missing cover image degrades to the generated cover rather than failing
  // the build: a broken deploy would take the whole site down over one image.
  let cover;
  if (data.cover) {
    if (!COVER_RE.test(data.cover)) {
      console.warn(`blog-data: ignoring cover "${data.cover}" on ${slug}; not an uploaded image path`);
    } else if (!fs.existsSync(path.join(ROOT, "public", data.cover))) {
      console.warn(`blog-data: ignoring cover "${data.cover}" on ${slug}; file not found in public/`);
    } else {
      cover = data.cover;
    }
  }

  return {
    slug,
    archived: data.archived === true,
    title: String(data.title),
    excerpt: String(data.excerpt),
    date: String(data.date),
    tone: data.tone ?? "teal",
    ...(data.author ? { author: String(data.author).trim() } : {}),
    ...(cover ? { cover } : {}),
    readingTime: readingTime(content).text,
    html: String(processor.processSync(content)),
  };
}

/** Written by the admin's re-order; absent until someone re-orders. */
const order = fs.existsSync(ORDER_FILE) ? JSON.parse(fs.readFileSync(ORDER_FILE, "utf8")) : [];
const rank = new Map((Array.isArray(order) ? order : []).map((slug, i) => [slug, i]));

const posts = fs
  .readdirSync(BLOG_DIR)
  .filter((file) => file.endsWith(".md"))
  .map((file) => compile(file.replace(/\.md$/, ""), fs.readFileSync(path.join(BLOG_DIR, file), "utf8")))
  // Archived posts stay in content/blog/ but never reach the site.
  .filter((post) => !post.archived)
  .map((post) => {
    delete post.archived;
    return post;
  })
  // The display order every consumer uses, so none of them re-sorts. Posts not
  // in order.json come first, newest first, then the rest in its order — the
  // same rule as `applyOrder` in src/lib/admin/posts.ts.
  .sort((a, b) => {
    const ra = rank.get(a.slug);
    const rb = rank.get(b.slug);
    if (ra === undefined && rb === undefined) return a.date < b.date ? 1 : a.date > b.date ? -1 : 0;
    if (ra === undefined) return -1;
    if (rb === undefined) return 1;
    return ra - rb;
  });

const banner = `// Generated by scripts/build-blog-data.mjs from content/blog/*.md.
// Do not edit by hand — edit the Markdown and rebuild (\`npm run blog:data\`).

import type { RawPost } from "./blog";

export const RAW_POSTS: RawPost[] = `;

fs.writeFileSync(OUT_FILE, `${banner}${JSON.stringify(posts, null, 2)};\n`);

console.log(`blog-data: ${posts.length} post(s) → src/lib/blog-data.ts`);
